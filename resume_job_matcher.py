def rank_candidates(resumes, jd):
    df = pd.DataFrame({'resume_text': [clean(r) for r in resumes], 'job_description_text': clean(jd)})
    df[['skill_score','skill_jaccard','n_matched','n_jd_skills','matched_skills','missing_skills']] = skill_features(df)
    df['exp_score'] = [exp_score(r, j) for r, j in zip(df.resume_text, df.job_description_text)]
    S = stage2_features(df, s1_tfidf.predict_proba(tfidf_pair(df)), s1_bert.predict_proba(bert_pair(df)))
    p = best.predict_proba(S)
    df['tfidf_score'] = S[:, 7]; df['bert_score'] = S[:, 6]
    df['label'] = [list(LABELS)[i] for i in p.argmax(1)]
    df['confidence'] = p.max(1); df['rank_score'] = p[:,2] + 0.5*p[:,1]
    return df.sort_values('rank_score', ascending=False).reset_index(drop=True)

def explain(row):
    return (f"{row.label} ({row.confidence:.0%}) | tfidf {row.tfidf_score:.2f}, bert {row.bert_score:.2f}, "
            f"skills {row.skill_score:.0%} ({row.n_matched}/{row.n_jd_skills}), exp {row.exp_score:.2f}\n"
            f"  matched: {', '.join(row.matched_skills) or 'none'}\n"
            f"  missing: {', '.join(row.missing_skills) or 'none'}")

