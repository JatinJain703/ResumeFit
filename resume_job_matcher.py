PAT = {s: re.compile(r'(?<![a-z0-9])' + re.escape(s) + r'(?![a-z0-9])') for s in SKILLS}

def extract_skills(text):
    t = text.lower()
    return {s for s, p in PAT.items() if p.search(t)}

def skill_features(df):
    rows = []
    for r, j in zip(df.resume_text, df.job_description_text):
        rs, js = extract_skills(r), extract_skills(j); inter = rs & js
        rows.append({'skill_score': len(inter)/len(js) if js else 0.0,
                     'skill_jaccard': len(inter)/len(rs | js) if (rs | js) else 0.0,
                     'n_matched': len(inter), 'n_jd_skills': len(js),
                     'matched_skills': sorted(inter), 'missing_skills': sorted(js - rs)})
    return pd.DataFrame(rows, index=df.index)

def years(text):
    m = re.findall(r'(\d{1,2})\s*\+?\s*(?:years|yrs)', text.lower())
    return max(map(int, m)) if m else None

def exp_score(res, jd):
    need, have = years(jd), years(res)
    if need is None: return 1.0
    if have is None: return 0.5
    return 1.0 if have >= need else have / need

