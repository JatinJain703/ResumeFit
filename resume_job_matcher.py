def ndcg10(df, proba):
    d = pd.DataFrame({'g': df.job_description_text.values, 'rel': df.label.map(LABELS).values, 's': proba[:,2] + 0.5*proba[:,1]})
    return np.mean([ndcg_score([g.rel.values], [g.s.values], k=10) for _, g in d.groupby('g') if len(g) > 1])

