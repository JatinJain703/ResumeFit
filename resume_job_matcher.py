def tfidf_pair(df):                  # element-wise product + |difference| of the two TF-IDF vectors
    R, J = tfidf.transform(df.resume_text), tfidf.transform(df.job_description_text)
    return sp.hstack([R.multiply(J), abs(R - J)]).tocsr()

def bert_pair(df):                   # same idea on the 384-d sentence embeddings
    R = np.vstack([vec(t) for t in df.resume_text]); J = np.vstack([vec(t) for t in df.job_description_text])
    return np.hstack([R * J, np.abs(R - J)])

def bert_cos(df):
    return np.array([float(vec(r) @ vec(j)) for r, j in zip(df.resume_text, df.job_description_text)])

