def chunks(text, size=200):
    w = text.split()
    return [' '.join(w[i:i+size]) for i in range(0, len(w), size)] or ['']

def embed_mean(text):
    e = bert.encode(chunks(text), normalize_embeddings=True).mean(axis=0)
    return e / np.linalg.norm(e)

