def within_job(df, cols):            # how each score compares with the OTHER candidates for the same job
    d = pd.DataFrame(cols, index=df.index); d['g'] = df.job_description_text.values; out = []
    for c in cols:
        grp = d.groupby('g')[c]
        out += [grp.rank(pct=True).values[:, None],
                ((d[c] - grp.transform('mean')) / (grp.transform('std').fillna(1) + 1e-6)).values[:, None]]
    return np.hstack(out)

def stage2_features(df, p_tfidf, p_bert):
    bcos = bert_cos(df)
    tcos = np.asarray(tfidf.transform(df.resume_text).multiply(tfidf.transform(df.job_description_text)).sum(1)).ravel()
    raw = np.c_[p_tfidf, p_bert, bcos, tcos, df.skill_score, df.skill_jaccard, df.n_matched, df.exp_score]
    wj  = within_job(df, {'t0': p_tfidf[:,0], 't2': p_tfidf[:,2], 'texp': p_tfidf[:,2] + .5*p_tfidf[:,1],
                          'b2': p_bert[:,2], 'bcos': bcos, 'tcos': tcos, 'sk': df.skill_score.values})
    return np.hstack([raw, wj])

